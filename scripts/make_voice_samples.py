r"""Listening samples for the speech-text rewrite: the 12 trickiest strings spoken BEFORE the rewrite (the old pronounce(): only AGMC/GCC/SUV respelled) and AFTER it
(speech_text.py), plus several spellings of "dirhams", numbers as digits vs words, time styles and phone-number styles.

  .venv\Scripts\python.exe scripts\make_voice_samples.py          # writes docs/voices/*.wav and docs/voices/README.md

Whisper cannot judge pronunciation reliably (its own word prior fills gaps), so these are for listening. Edit config/pronunciations.yaml and re-run to try a respelling.
"""
from __future__ import annotations

import sys
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dealer_core.config import load_config  # noqa: E402
from dealer_core.voice.speech_text import speech_text  # noqa: E402
from dealer_core.voice.tts import PRONUNCIATIONS, PiperSherpa, speech_chunks  # noqa: E402

OUT = ROOT / "docs" / "voices"

TRICKY = [
    "The 2019 BMW X5 is 209,000 dirhams with 71,000 km.",
    "It's AED 98,500, which is fixed.",
    "That is 209,000 AED for the Land Cruiser.",
    "I can do tomorrow at 4:00 PM or Saturday at 10:30 AM.",
    "You're booked for Saturday, 24 October at 4:00 PM.",
    "Is your number 050 123 4567?",
    "The Mercedes GLC 300 is 178,000 dirhams with 28,000 km.",
    "The 2022 BMW 320i and the BMW M3 Competition are at our AGMC showroom.",
    "The Mazda CX-5 and the Toyota RAV4 are both available.",
    "A 2021 Land Cruiser GXR with 122 hp.",
    "The Lexus RX 350 F Sport and the Audi Q7 55 TFSI.",
    "The Tesla Model 3 Long Range goes from 0 to 100 km/h in 5.6 seconds.",
]
DIRHAM_SPELLINGS = ["dirhams", "dirham", "durrhams", "dirrums", "deer hams", "dir hams", "dihr hams"]
TIME_STYLES = {"raw 4:00 PM": "I can do tomorrow at 4:00 PM.", "four PM": "I can do tomorrow at four PM.", "four P M": "I can do tomorrow at four P M.",
               "four in the afternoon": "I can do tomorrow at four in the afternoon.", "four o'clock": "I can do tomorrow at four o'clock in the afternoon."}
PHONE_STYLES = {"raw digits": "Your number is 050 123 4567.", "digits as words, no pauses": "Your number is zero five zero one two three four five six seven.",
                "grouped with commas (chosen)": "Your number is zero five zero, one two three, four five six seven.",
                "grouped with full stops (longer pauses)": "Your number is zero five zero. One two three. Four five six seven."}
NUMBER_STYLES = {"digits": "That is 209,000 dirhams.", "words": "That is two hundred and nine thousand dirhams.",
                 "words, no 'and'": "That is two hundred nine thousand dirhams."}


def legacy(text: str) -> str:
    """The old pronounce(): only the brand-letter respellings."""
    for pattern, spoken in PRONUNCIATIONS:
        text = pattern.sub(spoken, text)
    return text


def save(tts: PiperSherpa, spoken: str, path: Path) -> float:
    audio = np.concatenate([tts.synthesize(c) for c in speech_chunks(spoken)])
    pcm = (np.clip(audio, -1, 1) * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(tts.sample_rate)
        w.writeframes(pcm.tobytes())
    return len(pcm) / tts.sample_rate


def main() -> int:
    cfg = load_config()
    tts = PiperSherpa(ROOT / cfg.app.model_dir, cfg.tts.voice or "amy_medium", speaker=cfg.tts.speaker)
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.wav"):
        old.unlink()
    lines = [f"# Voice samples ({tts.name})", "", "Generated by `scripts/make_voice_samples.py`. Listen to each pair; the text given to the voice is shown. "
             "To change a respelling edit `config/pronunciations.yaml` and re-run.", "",
             "## A. The 12 trickiest strings, before and after the rewrite", "", "| # | file | text given to the voice |", "|---|---|---|"]
    for i, text in enumerate(TRICKY, 1):
        before, after = legacy(text), legacy(speech_text(text))
        save(tts, before, OUT / f"{i:02d}_before.wav")
        save(tts, after, OUT / f"{i:02d}_after.wav")
        lines.append(f"| {i} | `{i:02d}_before.wav` | {before} |")
        lines.append(f"| {i} | `{i:02d}_after.wav` | {after} |")
    lines += ["", "## B. Spellings of \"dirhams\" (sentence: \"The price is 62,500 ___.\")", "", "| file | spelling |", "|---|---|"]
    for k, sp in enumerate(DIRHAM_SPELLINGS, 1):
        spoken = legacy(f"The price is {speech_text('62,500')} {sp}.")
        save(tts, spoken, OUT / f"B{k}_dirhams_{sp.replace(' ', '-')}.wav")
        lines.append(f"| `B{k}_dirhams_{sp.replace(' ', '-')}.wav` | {spoken} |")
    lines += ["", "## C. Numbers as digits or as words", "", "| file | text |", "|---|---|"]
    for k, (label, text) in enumerate(NUMBER_STYLES.items(), 1):
        spoken = legacy(speech_text(text))
        save(tts, spoken, OUT / f"C{k}_numbers_{label.split(',')[0].replace(' ', '-')}{'' if label in ('digits', 'words') else '-noand'}.wav")
        lines.append(f"| `C{k}` {label} | {spoken} |")
    lines += ["", "## D. Time styles", "", "| file | text |", "|---|---|"]
    for k, (label, text) in enumerate(TIME_STYLES.items(), 1):
        spoken = legacy(speech_text(text) if label == "raw 4:00 PM" and False else text if label != "raw 4:00 PM" else text)
        save(tts, spoken, OUT / f"D{k}_time_{label.replace(' ', '-').replace(':', '').replace(chr(39), '')}.wav")
        lines.append(f"| `D{k}` {label} | {spoken} |")
    lines += ["", "## E. Phone-number styles", "", "| file | text |", "|---|---|"]
    for k, (label, text) in enumerate(PHONE_STYLES.items(), 1):
        spoken = legacy(text)
        save(tts, spoken, OUT / f"E{k}_phone_{label.split(' (')[0].replace(' ', '-').replace(',', '')}.wav")
        lines.append(f"| `E{k}` {label} | {spoken} |")
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(list(OUT.glob('*.wav')))} samples and README.md to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
